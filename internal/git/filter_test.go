package git

import "testing"

func TestFilterDefaults(t *testing.T) {
	f := NewFilter(nil, nil)
	tests := map[string]bool{
		"main.go":                 true,
		"internal/x/y.go":         true,
		"vendor/lib/a.go":         false,
		"web/node_modules/a/b.js": false,
		"third_party/x.c":         false,
		"dist/app.js":             false,
		"build/out.o":             false,
		"builder/a.go":            true, // prefix of a default dir is not the dir
		"go.sum":                  false,
		"sub/package-lock.json":   false,
		"yarn.lock":               false,
		"api/foo.pb.go":           false,
		"x/schema_gen.go":         false,
		"static/app.min.js":       false,
		"static/app.js":           true,
	}
	for p, want := range tests {
		if got := f.Allow(p); got != want {
			t.Errorf("Allow(%q) = %v, want %v", p, got, want)
		}
	}
}

func TestFilterIncludeExclude(t *testing.T) {
	f := NewFilter([]string{"vendor/keep/**"}, []string{"*.md", "docs/"})
	tests := map[string]bool{
		"vendor/keep/a.go":  true, // include rescues from default exclusion
		"vendor/other/a.go": false,
		"README.md":         false, // exclude by basename glob
		"a/b/NOTES.md":      false,
		"docs/x.go":         false, // dir exclude
		"src/docs.go":       true,
		"src/a.go":          true,
	}
	for p, want := range tests {
		if got := f.Allow(p); got != want {
			t.Errorf("Allow(%q) = %v, want %v", p, got, want)
		}
	}
}

func TestFilterMarkExcluded(t *testing.T) {
	f := NewFilter(nil, nil)
	f.MarkExcluded("gen/a.go")
	if f.Allow("gen/a.go") {
		t.Error("marked path still allowed")
	}
}

func TestHasGeneratedHeader(t *testing.T) {
	gen := []string{"// Code generated by protoc. DO NOT EDIT.", "package x"}
	if !HasGeneratedHeader(gen) {
		t.Error("should detect generated header")
	}
	late := []string{"a", "b", "c", "d", "e", "// Code generated by x; DO NOT EDIT."}
	if HasGeneratedHeader(late) {
		t.Error("header after line 5 must not count")
	}
	if HasGeneratedHeader([]string{"// Code generated by hand"}) {
		t.Error("needs DO NOT EDIT too")
	}
}
